// Generates src/design/tokens.ts and src/design/tokens.css from design/design/tokens.json.
// Run with: npm run tokens
import { readFileSync, writeFileSync } from "node:fs";

const src = JSON.parse(readFileSync("design/design/tokens.json", "utf8"));
const kebab = (s) => s.replace(/[A-Z]/g, (c) => "-" + c.toLowerCase());
const vars = (o, prefix) => Object.entries(o).map(([k, v]) => `  --${prefix}${kebab(k)}: ${v};`);

const { light, dark } = src.color;
// Every role has a dark value now; anything missing still falls back to light rather than to nothing.
const fullDark = { ...light, ...dark };
const glass = (g) => [
  ...["g1", "g2", "g3"].map((k) => `  --glass-${k.slice(1)}: ${g[k]};`),
  ...["solid1", "solid2", "solid3"].map((k) => `  --glass-solid-${k.slice(5)}: ${g[k]};`),
  `  --glass-edge: ${g.edge};`,
  `  --glass-edge-low: ${g.edgeLow};`,
  `  --glass-line: ${g.line};`,
  `  --glass-shadow: ${g.shadow};`,
];
const glassShared = ["g1", "g2", "g3"].map((k) => `  --glass-blur-${k.slice(1)}: blur(${src.glass.blur[k]}) saturate(${src.glass.saturate[k]});`);

const shadow = vars(src.shadow, "shadow-");
const radius = Object.entries(src.radius).map(([k, v]) => `  --radius-${kebab(k)}: ${v}px;`);
const size = Object.entries(src.size).map(([k, v]) => `  --size-${kebab(k)}: ${v}px;`);
const space = src.space.map((v, i) => `  --space-${i + 1}: ${v}px;`);
const layout = [
  `  --rail-width: ${src.layout.railWidth}px;`,
  `  --titlebar-height: ${src.layout.titleBarHeight}px;`,
  `  --content-padding-x: ${src.layout.contentPaddingX}px;`,
  `  --rail-collapsed: ${src.layout.railCollapsed}px;`,
  `  --tray-height: ${src.layout.trayHeight}px;`,
];
const fonts = [
  `  --font-display: "Fraunces Variable", Georgia, serif;`,
  `  --font-ui: "${src.font.ui.family}", "Segoe UI", system-ui, sans-serif;`,
  `  --font-mono: "${src.font.mono.family}", ui-monospace, monospace;`,
];

const css = `/* Generated by scripts/gen-tokens.mjs from design/design/tokens.json. Do not edit. */
:root {
  color-scheme: light;
${[...vars(light, "c-"), ...glass(src.glass.light), ...glassShared, ...shadow, ...radius, ...size, ...space, ...layout, ...fonts].join("\n")}
}
:root[data-theme="dark"] {
  color-scheme: dark;
${[...vars(fullDark, "c-"), ...glass(src.glass.dark)].join("\n")}
}
`;
writeFileSync("src/design/tokens.css", css);
writeFileSync(
  "src/design/tokens.ts",
  `// Generated by scripts/gen-tokens.mjs from design/design/tokens.json. Do not edit.
export const tokens = ${JSON.stringify(
    { color: { light, dark: fullDark }, glass: src.glass, size: src.size, space: src.space, radius: src.radius, layout: src.layout },
    null,
    2,
  )} as const;
`,
);
